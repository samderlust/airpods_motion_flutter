import 'headphone_device.dart';
import 'headphone_quaternion.dart';
import 'headphone_vector3.dart';

/// A full 6-DoF head-motion telemetry frame from `CMHeadphoneMotionManager`
/// or [AirPodsMotionSimulator].
class HeadphoneMotionSample {
  /// Creates a [HeadphoneMotionSample].
  const HeadphoneMotionSample({
    required this.pitchDeg,
    required this.rollDeg,
    required this.yawDeg,
    this.quaternion = HeadphoneQuaternion.identity,
    this.rotationRate = HeadphoneVector3.zero,
    this.userAcceleration = HeadphoneVector3.zero,
    this.gravity = HeadphoneVector3.zero,
    this.magneticField,
    double? accelerationMagnitude,
    this.sensorLocation = HeadphoneSensorLocation.unknown,
    this.isCalibrated = false,
    this.isSimulated = false,
    required this.timestampMs,
  }) : accelerationMagnitude = accelerationMagnitude ?? 0.0;

  /// Deserializes a [HeadphoneMotionSample] from a platform channel or JSON map.
  factory HeadphoneMotionSample.fromMap(Map<String, dynamic> map) {
    final userAccMap = _asStringMap(map['userAcceleration']);
    final userAcceleration =
        userAccMap != null
            ? HeadphoneVector3.fromMap(userAccMap)
            : HeadphoneVector3.zero;

    final quaternionMap = _asStringMap(map['quaternion']);
    final rotationRateMap = _asStringMap(map['rotationRate']);
    final gravityMap = _asStringMap(map['gravity']);
    final magneticFieldMap = _asStringMap(map['magneticField']);

    final rawMagnitude = (map['accelerationMagnitude'] as num?)?.toDouble();

    return HeadphoneMotionSample(
      pitchDeg: (map['pitchDeg'] as num?)?.toDouble() ?? 0.0,
      rollDeg: (map['rollDeg'] as num?)?.toDouble() ?? 0.0,
      yawDeg: (map['yawDeg'] as num?)?.toDouble() ?? 0.0,
      quaternion:
          quaternionMap != null
              ? HeadphoneQuaternion.fromMap(quaternionMap)
              : HeadphoneQuaternion.identity,
      rotationRate:
          rotationRateMap != null
              ? HeadphoneVector3.fromMap(rotationRateMap)
              : HeadphoneVector3.zero,
      userAcceleration: userAcceleration,
      gravity:
          gravityMap != null
              ? HeadphoneVector3.fromMap(gravityMap)
              : HeadphoneVector3.zero,
      magneticField:
          magneticFieldMap != null
              ? HeadphoneVector3.fromMap(magneticFieldMap)
              : null,
      accelerationMagnitude: rawMagnitude ?? userAcceleration.magnitude,
      sensorLocation: HeadphoneSensorLocation.fromWireValue(
        map['sensorLocation'] as String?,
      ),
      isCalibrated: (map['isCalibrated'] as bool?) ?? false,
      isSimulated: (map['isSimulated'] as bool?) ?? false,
      timestampMs: (map['timestampMs'] as num?)?.toInt() ?? 0,
    );
  }

  /// Calibrated pitch angle in degrees (`+` looking up, `-` looking down).
  final double pitchDeg;

  /// Calibrated roll angle in degrees (`+` tilting right, `-` tilting left).
  final double rollDeg;

  /// Calibrated yaw angle in degrees (`-` turning left, `+` turning right).
  final double yawDeg;

  /// Calibrated orientation quaternion `(x, y, z, w)`.
  final HeadphoneQuaternion quaternion;

  /// Angular velocity around X, Y, Z axes in radians per second (`rad/s`).
  final HeadphoneVector3 rotationRate;

  /// User-induced linear acceleration (gravity removed) in G.
  final HeadphoneVector3 userAcceleration;

  /// Estimated gravity vector in G.
  final HeadphoneVector3 gravity;

  /// Optional calibrated magnetic field vector in microteslas (µT).
  final HeadphoneVector3? magneticField;

  /// Euclidean magnitude of [userAcceleration] (`||a||`) in G.
  final double accelerationMagnitude;

  /// Active IMU earbud location.
  final HeadphoneSensorLocation sensorLocation;

  /// Whether the sample is relative to a calibrated zero-point reference attitude.
  final bool isCalibrated;

  /// Whether this sample was generated by the simulator or trace replay.
  final bool isSimulated;

  /// Epoch timestamp in milliseconds when the frame was captured.
  final int timestampMs;

  /// Returns a copy of this sample with the specified fields updated.
  HeadphoneMotionSample copyWith({
    double? pitchDeg,
    double? rollDeg,
    double? yawDeg,
    HeadphoneQuaternion? quaternion,
    HeadphoneVector3? rotationRate,
    HeadphoneVector3? userAcceleration,
    HeadphoneVector3? gravity,
    HeadphoneVector3? magneticField,
    double? accelerationMagnitude,
    HeadphoneSensorLocation? sensorLocation,
    bool? isCalibrated,
    bool? isSimulated,
    int? timestampMs,
  }) {
    return HeadphoneMotionSample(
      pitchDeg: pitchDeg ?? this.pitchDeg,
      rollDeg: rollDeg ?? this.rollDeg,
      yawDeg: yawDeg ?? this.yawDeg,
      quaternion: quaternion ?? this.quaternion,
      rotationRate: rotationRate ?? this.rotationRate,
      userAcceleration: userAcceleration ?? this.userAcceleration,
      gravity: gravity ?? this.gravity,
      magneticField: magneticField ?? this.magneticField,
      accelerationMagnitude:
          accelerationMagnitude ?? this.accelerationMagnitude,
      sensorLocation: sensorLocation ?? this.sensorLocation,
      isCalibrated: isCalibrated ?? this.isCalibrated,
      isSimulated: isSimulated ?? this.isSimulated,
      timestampMs: timestampMs ?? this.timestampMs,
    );
  }

  /// Serializes this sample to a JSON-compatible map for trace recording & replay.
  Map<String, dynamic> toJson() => <String, dynamic>{
    'pitchDeg': pitchDeg,
    'rollDeg': rollDeg,
    'yawDeg': yawDeg,
    'quaternion': quaternion.toJson(),
    'rotationRate': rotationRate.toJson(),
    'userAcceleration': userAcceleration.toJson(),
    'gravity': gravity.toJson(),
    if (magneticField != null) 'magneticField': magneticField!.toJson(),
    'accelerationMagnitude': accelerationMagnitude,
    'sensorLocation': sensorLocation.name,
    'isCalibrated': isCalibrated,
    'isSimulated': isSimulated,
    'timestampMs': timestampMs,
  };

  static Map<String, dynamic>? _asStringMap(Object? raw) {
    if (raw is Map<String, dynamic>) {
      return raw;
    }
    if (raw is Map) {
      return Map<String, dynamic>.from(raw);
    }
    return null;
  }

  @override
  bool operator ==(Object other) =>
      identical(this, other) ||
      other is HeadphoneMotionSample &&
          runtimeType == other.runtimeType &&
          pitchDeg == other.pitchDeg &&
          rollDeg == other.rollDeg &&
          yawDeg == other.yawDeg &&
          quaternion == other.quaternion &&
          rotationRate == other.rotationRate &&
          userAcceleration == other.userAcceleration &&
          gravity == other.gravity &&
          magneticField == other.magneticField &&
          accelerationMagnitude == other.accelerationMagnitude &&
          sensorLocation == other.sensorLocation &&
          isCalibrated == other.isCalibrated &&
          isSimulated == other.isSimulated &&
          timestampMs == other.timestampMs;

  @override
  int get hashCode => Object.hash(
    pitchDeg,
    rollDeg,
    yawDeg,
    quaternion,
    rotationRate,
    userAcceleration,
    gravity,
    magneticField,
    accelerationMagnitude,
    sensorLocation,
    isCalibrated,
    isSimulated,
    timestampMs,
  );

  @override
  String toString() =>
      'HeadphoneMotionSample(pitchDeg: $pitchDeg, rollDeg: $rollDeg, '
      'yawDeg: $yawDeg, accelerationMagnitude: $accelerationMagnitude, '
      'sensorLocation: $sensorLocation, isCalibrated: $isCalibrated, '
      'isSimulated: $isSimulated, timestampMs: $timestampMs)';
}
